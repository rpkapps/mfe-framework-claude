/** Comic Shanns is monospaced at 0.55em, measured the same way. */
const COMIC_ADVANCE = 55

/** Excalidraw's `FONT_FAMILY`; only these two are used, and it embeds both. */
export const FONT = { hand: 5, mono: 8 }

/** Excalidraw's own line height for both faces. */
const LINE_HEIGHT = 1.25

/** What Excalidraw leaves between a container's edge and the text bound inside it. */
const BOUND_TEXT_PADDING = 5

export const STROKE = {
  ink: '#1e1e1e',
  muted: '#868e96',
  red: '#e03131',
  blue: '#1971c2',
  green: '#2f9e44',
}

/**
 * One hue per concern, the same in all ten diagrams, all from Excalidraw's own palette.
 * A diagram in which a colour carries meaning says so in a legend.
 */
